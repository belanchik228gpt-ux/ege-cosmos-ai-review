function copyCard(task: ExamWorkshopTask): ExamWorkshopTask {
  return {
    ...task,
    officialRequirements: [...task.officialRequirements],
    tips: [...task.tips],
    pages: [...task.pages],
    demoPages: task.demoPages && [...task.demoPages],
    contentCodes: task.contentCodes && [...task.contentCodes],
    requirementCodes: task.requirementCodes && [...task.requirementCodes],
  };
}

/** Each subject's own numbering starts at 1. Returned data cannot mutate the registry. */
export function getExamTasks(subject: SubjectId): ExamWorkshopTask[] {
  return (tasks[subject] ?? []).map(copyCard);
}

export function getExamTask(subject: SubjectId, number: number): ExamWorkshopTask | undefined {
  if (!Number.isInteger(number)) return undefined;
  const task = tasks[subject]?.find((entry) => entry.number === number);
  return task ? copyCard(task) : undefined;
}

