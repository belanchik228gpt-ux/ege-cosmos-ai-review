export const humanitiesExamples: Array<{ subject: SchoolUnit['subject']; topic: string }> =
  families.map(({ subject, topic }) => ({ subject, topic }));

export function humanitiesDrawing(unit: SchoolUnit, topic: string): TutorDrawing | undefined {
  const focus = (topic.trim() || unit.title)
    .toLocaleLowerCase('ru')
    .replaceAll('ё', 'е')
    .replace(/\s+/gu, ' ')
    .trim();
  const family = families.find(
    (candidate) => candidate.subject === unit.subject && candidate.match.test(focus),
  );
  if (!family) return undefined;
  // Return independent data: a player or caller cannot corrupt later lessons by mutating a frame.
  return {
    ...family.drawing,
    steps: family.drawing.steps.map((step) => ({
      ...step,
      labels: step.labels ? [...step.labels] : undefined,
      values: step.values ? [...step.values] : undefined,
    })),
  };
}
