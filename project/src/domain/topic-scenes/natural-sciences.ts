import type { TutorDrawing } from '../cloud-learning';
import type { SchoolUnit } from '../school-program/types';

type Subject = 'physics' | 'chemistry' | 'biology' | 'geography';
type Step = TutorDrawing['steps'][number];
type Family = { subject: Subject; topic: string; aliases: string[]; drawing: TutorDrawing };
const families: Family[] = [];
const step = (caption: string, formula?: string, labels?: string[]): Step => ({
  caption,
  ...(formula ? { formula } : {}),
  ...(labels ? { labels } : {}),
});
function add(
  subject: Subject,
  topic: string,
  aliases: string[],
  kind: TutorDrawing['kind'],
  title: string,
  steps: Step[],
  figure?: TutorDrawing['figure'],
) {
  families.push({
    subject,
    topic,
    aliases,
    drawing: { kind, title: `Авторский пример · ${title}`, steps, ...(figure ? { figure } : {}) },
  });
}
const frames = (steps: Step[], values?: number[], labels?: string[]): Step[] =>
  steps.map((s) => ({
    ...s,
    ...(values ? { values: [...values] } : {}),
    ...(labels ? { labels: [...labels] } : {}),
  }));

