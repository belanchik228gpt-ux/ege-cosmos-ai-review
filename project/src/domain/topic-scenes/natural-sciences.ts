// Exact aliases prevent, for example, nuclear half-life from selecting mechanical oscillations,
// osmotic pressure from selecting a solid contact, or RNA from selecting DNA pairing.
const normalize = (value: string) =>
  value
    .normalize('NFKC')
    .toLocaleLowerCase('ru')
    .replaceAll('ё', 'е')
    .replace(/[\u00ad\u200b]/g, '')
    .replace(/[‐‑‒–—]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[.!]+$/, '')
    .trim();
const index = new Map<string, Family>();
for (const family of families)
  for (const topic of [family.topic, ...family.aliases]) {
    const key = `${family.subject}:${normalize(topic)}`;
    if (index.has(key) && index.get(key) !== family)
      throw new Error('Duplicate natural-science scene alias');
    index.set(key, family);
  }
export const naturalSciencesExamples = families.map(({ subject, topic }) => ({ subject, topic }));
export function naturalSciencesDrawing(unit: SchoolUnit, topic: string): TutorDrawing | undefined {
  if (typeof topic !== 'string' || !topic.trim() || topic.length > 1400) return undefined;
  const family = index.get(`${unit.subject}:${normalize(topic)}`);
  if (!family) return undefined;
  // Every call owns its arrays; replay, preview or validation cannot modify the registry.
  return {
    ...family.drawing,
    steps: family.drawing.steps.map((s) => ({
      ...s,
      ...(s.values ? { values: [...s.values] } : {}),
      ...(s.labels ? { labels: [...s.labels] } : {}),
    })),
  };
}
