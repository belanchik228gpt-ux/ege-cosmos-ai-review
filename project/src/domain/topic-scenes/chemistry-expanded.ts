const normalize = (v: string) =>
  v
    .normalize('NFKC')
    .toLocaleLowerCase('ru')
    .replaceAll('ё', 'е')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[.!]+$/, '')
    .trim();
const index = new Map<string, number>();
families.forEach((family, i) =>
  [family.topic, ...family.aliases].forEach((topic) => index.set(normalize(topic), i)),
);
export const chemistryExpandedExamples = families.map(({ topic }, scenario) => ({
  subject: 'chemistry' as const,
  topic,
  scenario,
}));
export function chemistryExpandedDrawing(
  unit: SchoolUnit,
  topic: string,
): TutorDrawing | undefined {
  if (unit.subject !== 'chemistry' || typeof topic !== 'string' || topic.length > 1400)
    return undefined;
  const scenario = index.get(normalize(topic));
  if (scenario === undefined) return undefined;
  const family = families[scenario];
  return {
    kind: 'concept',
    figure: 'chemistry-reaction',
    title: `Авторский пример · ${family.title}`,
    steps: family.steps.map((s, stage) => ({ ...s, values: [scenario, stage] })),
  };
}
