/** Match complete authored subtopic names, never the enclosing unit's broad keywords.
 * Typography-only normalization accepts catalogue sentence punctuation without
 * turning an unknown narrow question into a supposedly relevant scene. */
function normalize(topic: string): string {
  return topic
    .normalize('NFKC')
    .toLocaleLowerCase('ru')
    .replaceAll('ё', 'е')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[.!?]+$/, '')
    .trim();
}
export const mathInformaticsExamples: Array<{ subject: Subject; topic: string }> = entries.map(
  (entry) => ({ subject: entry.subject, topic: entry.topics[0] }),
);

export function mathInformaticsDrawing(unit: SchoolUnit, topic: string): TutorDrawing | undefined {
  if ((unit.subject !== 'math' && unit.subject !== 'informatics') || !topic.trim()) return;
  const selected = normalize(topic);
  const entry = entries.find(
    (item) =>
      item.subject === unit.subject && item.topics.some((alias) => normalize(alias) === selected),
  );
  if (!entry) return;
  return {
    ...entry.drawing,
    steps: entry.drawing.steps.map((frame) => ({
      ...frame,
      ...(frame.values ? { values: [...frame.values] } : {}),
      ...(frame.labels ? { labels: [...frame.labels] } : {}),
    })),
  };
}
