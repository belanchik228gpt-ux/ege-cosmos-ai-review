type Subject = 'math' | 'informatics';
type FigureDrawing = TutorDrawing & { figure?: 'right-triangle' | 'tree' | 'interval' };
type Entry = { subject: Subject; topics: string[]; drawing: FigureDrawing };
const entries: Entry[] = [];
const step = (
  caption: string,
  formula?: string,
  values?: number[],
  labels?: string[],
): TutorDrawing['steps'][number] => ({ caption, formula, values, labels });
function add(
  subject: Subject,
  topics: string[],
  title: string,
  steps: TutorDrawing['steps'],
  kind: TutorDrawing['kind'] = 'algebra',
  figure?: FigureDrawing['figure'],
) {
  entries.push({
    subject,
    topics,
    drawing: { kind, title: `Авторский пример · ${title}`, steps, ...(figure ? { figure } : {}) },
  });
}
