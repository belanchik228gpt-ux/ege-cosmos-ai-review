/** Every catalogue node has a safe procedural overview, including unfamiliar future titles. */
export function curriculumVisualFamily(node: CurriculumSceneNode): CurriculumVisualFamily {
  const title = node.title.toLocaleLowerCase('ru');
  const head = title.split(/[.!?]/)[0];
  const section = node.section.toLocaleLowerCase('ru');
  const text = `${title} ${(node.keywords ?? []).join(' ').toLocaleLowerCase('ru')}`;
  if (node.subject === 'math') {
    if (/модул/.test(text)) return 'absolute';
    if (/прогресси/.test(text)) return 'algebra';
    if (/вероятност|статист|комбинатор|случайн|выборк/.test(text)) return 'chance';
    if (
      /стереометр|пространств|объ[её]м|многогран|призм|пирамид|цилиндр|конус|шар|сфер|тела и поверхности/.test(
        text,
      )
    )
      return 'solid';
    if (
      /функци|график|производн|первообразн|интеграл|координат/.test(
        node.title.toLocaleLowerCase('ru'),
      )
    )
      return 'graph';
    if (
      /геометр|треугол|окруж|угол|площад|вектор|медиан|биссектрис|касател|четыр[её]хугол/.test(text)
    )
      return 'geometry';
    if (/функци|график|производн|первообразн|интеграл|координат/.test(text)) return 'graph';
    return 'algebra';
  }
  if (node.subject === 'russian') {
    // Broad sections mention speech even when this title concerns orthography or syntax.
    if (/орфограф|орфограмм|правопис|написан|не и ни|н и нн/.test(head)) return 'spelling';
    if (/синтакс|пунктуац|предложен|запят|словосочет/.test(head)) return 'syntax';
    if (
      /част[ьи] речи|морфологи|существительн|прилагательн|числительн|местоимен|глагол|нареч|причасти|деепричасти/.test(
        head,
      )
    )
      return 'morphology';
    if (/сочинен|текст|речь|речев|культур[аы] речи|стил|аргумент|коммуникац/.test(head))
      return 'writing';
    if (/синтакс|пунктуац|предложен|запят|словосочет/.test(text)) return 'syntax';
    if (/орфограф|орфограмм|правопис|написан|гласн|согласн|букв|не и ни|н и нн/.test(text))
      return 'spelling';
    return 'morphology';
  }
  if (node.subject === 'history') {
    if (
      /карт|территор|войн|битв|поход|географ|границ|освоен|колони|международ|внешняя политика/.test(
        text,
      )
    )
      return 'map';
    if (/документ|договор|закон|манифест|источник|конституц|летопис|реформ/.test(text))
      return 'document';
    if (/княз|правител|император|личност|деятел|династи|монарх|царств/.test(text)) return 'person';
    return 'causes';
  }
  // The economic law of demand is not a legal norm. Use the catalogue's subject section.
  if (/правовое регулирование|правоведен/.test(section)) return 'law';
  if (/политическая сфера|политологи/.test(section)) return 'politics';
  if (/экономическая жизнь|введение в экономику/.test(section)) return 'market';
  if (/социальная сфера|человек в обществе|духовная культура/.test(section)) return 'groups';
  if (/право|правов|закон|юрид|конституц|суд|договор/.test(head)) return 'law';
  if (/полит|государств|власт|демократ|выбор|парти/.test(head)) return 'politics';
  if (
    /эконом|рын|спрос|предложен|деньг|финанс|банк|налог|инфляц|производств|собственност/.test(text)
  )
    return 'market';
  return 'groups';
}

function makeSteps(id: string, entries: Array<[string, string, string?]>): SceneStep[] {
  return entries.map(([title, narration, formula], index) => ({
    id: `${id}-${index + 1}`,
    title,
    narration,
    formula,
    durationMs: formula ? 4700 : 4100,
    visualAction: `route-stage-${index + 1}`,
    highlights: [title],
  }));
}

