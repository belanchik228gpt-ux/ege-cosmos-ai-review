export function createCurriculumScene(node: CurriculumSceneNode): LessonScene {
  if (node.id === 'math-absolute') return absoluteLessonScene;
  const family = curriculumVisualFamily(node),
    route = curriculumVisualRoutes[family];
  const steps = makeSteps(node.id, route.steps);
  return {
    id: `curriculum-${node.id}`,
    subject: node.subject,
    topic: node.id,
    title: route.title,
    eyebrow: 'ВИЗУАЛЬНАЯ КАРТА ТЕМЫ',
    autoplay: true,
    replayable: true,
    durationMs: steps.reduce((sum, step) => sum + step.durationMs, 0),
    steps,
    reducedMotionFrame: { step: steps.length - 1, description: route.title },
    question: route.question,
  };
}
