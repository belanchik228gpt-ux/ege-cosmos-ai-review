import type { LessonScene, SceneStep } from './types';

type StepInput = [title: string, narration: string, visualAction: string, formula?: string];
function define(
  id: string,
  subject: LessonScene['subject'],
  title: string,
  eyebrow: string,
  question: string,
  input: StepInput[],
): LessonScene {
  const steps: SceneStep[] = input.map(([stepTitle, narration, visualAction, formula], i) => ({
    id: `${id}-${i}`,
    title: stepTitle,
    narration,
    visualAction,
    formula,
    durationMs: i === input.length - 1 ? 6500 : 4200,
    highlights: [visualAction],
  }));
  return {
    id,
    subject,
    topic: title,
    title,
    eyebrow,
    question,
    autoplay: true,
    replayable: true,
    steps,
    durationMs: steps.reduce((sum, step) => sum + step.durationMs, 0),
    reducedMotionFrame: { step: steps.length - 1, description: question },
  };
}

