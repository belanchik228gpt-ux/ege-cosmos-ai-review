import {chromium} from 'playwright';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:5173');
await page.getByPlaceholder('Твоё имя').fill('Саша');
await page.getByRole('button',{name:'Начнём знакомство',exact:true}).click();
await page.getByRole('button',{name:'Продолжить занятие',exact:true}).click();
await page.locator('.scene-player').waitFor();
await page.getByRole('button',{name:'Пауза',exact:true}).click();
await page.locator('.scene-player').scrollIntoViewIfNeeded();
await page.screenshot({path:'docs/scene-review/rectangle-1280-initial.png'});
await page.getByRole('button',{name:'Шаг 8: Заполним всю фигуру',exact:true}).click();
await page.waitForFunction(() => [...document.querySelectorAll('.sc-reveal')].every(el => Number(getComputedStyle(el).opacity) === (el.classList.contains('sc-visible') ? 1 : 0)) && [...document.querySelectorAll('.sc-visible .sc-cell')].every(el => Number(getComputedStyle(el).opacity) === 1));
await page.waitForTimeout(1000);
await page.screenshot({path:'docs/scene-review/rectangle-1280-grid.png'});
console.log(JSON.stringify({url:page.url(),errors,sceneBox:await page.locator('.scene-player').boundingBox(),buttons:await page.locator('.sc-controls').innerText(),heading:await page.locator('.sc-explanation h3').innerText()}));
await page.setViewportSize({width:390,height:844});
await page.locator('.scene-player').scrollIntoViewIfNeeded();
await page.screenshot({path:'docs/scene-review/rectangle-390-grid.png'});
console.log(JSON.stringify({viewport:'390x844',sceneBox:await page.locator('.scene-player').boundingBox(),overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await browser.close();
