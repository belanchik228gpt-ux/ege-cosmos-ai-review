import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve('katex/package.json'));
let css = await fs.readFile(path.join(root, 'dist/katex.min.css'), 'utf8');
const fontFaces = [...css.matchAll(/@font-face\{[^}]+\}/g)];
for (const [face] of fontFaces) {
  const file = face.match(/url\((?:["'])?(fonts\/[^)"']+\.woff2)(?:["'])?\)/)?.[1];
  if (!file) throw new Error('KaTeX font has no WOFF2 source');
  const data = await fs.readFile(path.join(root, 'dist', file));
  css = css.replace(
    face,
    face.replace(
      /src:[^;}]*/,
      `src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2')`,
    ),
  );
}
if (/url\((?!data:)/.test(css)) throw new Error('Export CSS still has a non-embedded URL');
const notice = await fs.readFile(path.join(root, 'LICENSE'), 'utf8');
css = `/* KaTeX font and stylesheet license:\n${notice.replaceAll('*/', '* /')}\n*/\n${css}`;
const output = new URL('../shared/katex-export-assets.mjs', import.meta.url);
await fs.writeFile(
  output,
  `// Generated by scripts/build-export-fonts.mjs; do not edit.\n/*\n${notice.replaceAll('*/', '* /')}\n*/\nexport const katexExportCss = ${JSON.stringify(css)};\n`,
);
console.log(
  JSON.stringify({
    fonts: fontFaces.length,
    cssBytes: Buffer.byteLength(css),
    output: output.pathname,
  }),
);
