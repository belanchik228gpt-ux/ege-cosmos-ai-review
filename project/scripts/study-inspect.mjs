await page.screenshot({path:'test-results/study-preview/topic.png',fullPage:true});
await page.getByRole('button',{name:'Объяснение в сцене',exact:true}).click();
await page.waitForTimeout(1400);
await page.screenshot({path:'test-results/study-preview/scene.png',fullPage:true});
await browser.close();
