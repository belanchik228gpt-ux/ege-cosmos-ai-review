import { _electron as electron } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const exe=path.resolve('release/win-unpacked/EGE Cosmos.exe');
const out=path.resolve('docs/verification/skip-motion-final-0.7.5');
const profile=path.resolve(`test-results/skip-motion-final-${Date.now()}`);
await fs.mkdir(out,{recursive:true});
const report={status:'running',exe,profile,checks:[],screenshots:[],errors:[],asarSha256:createHash('sha256').update(await fs.readFile(path.join(path.dirname(exe),'resources/app.asar'))).digest('hex')};
let app,page;
const button=name=>page.getByRole('button',{name,exact:true});
const nav=name=>page.locator('.studio-sidebar').getByRole('button',{name,exact:true});
const state=()=>page.evaluate(()=>window.cosmos.loadState());
async function shot(name){const file=path.join(out,`${name}.png`);await page.screenshot({path:file});report.screenshots.push(file);}
try{
 app=await electron.launch({executablePath:exe,env:{...process.env,COSMOS_USER_DATA:profile,COSMOS_DOCUMENTS_DIR:path.join(profile,'documents')},timeout:45000});
 page=await app.firstWindow();page.setDefaultTimeout(15000);page.on('pageerror',e=>report.errors.push(e.message));
 await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.setIgnoreMouseEvents(true);w.setContentSize(1440,900);});
 await page.locator('.welcome-modal input').fill('Проверка пропуска и анимаций');await button('Начнём знакомство').click();
 await page.locator('.school-mode-switch').getByRole('button',{name:'ЕГЭ',exact:true}).click();
 await nav('Все темы ЕГЭ').click();
 if(await button('Общий каталог тем').isVisible())await button('Общий каталог тем').click();
 const card=page.locator('.studio-topic-card').first();
 const title=await card.locator('h2').innerText();
 await card.locator('button').filter({hasText:/^Пропустить$/}).click();
 assert.match(await card.innerText(),/Пропущено вручную · 100%/);
 await shot('01-ege-skip');
 await page.waitForTimeout(400);const skippedState=await state();const skippedId=Object.keys(skippedState.egeTopicSkips)[0];
 report.checks.push({name:'EGE manual skip',title,skippedId,display:await card.innerText()});
 await card.locator('button').filter({hasText:/^Вернуть$/}).click();
 assert.match(await card.innerText(),/Пройдено занятие · 0%/);
 report.checks.push({name:'EGE undo',display:await card.innerText()});
 await card.locator('button').filter({hasText:/^Пропустить$/}).click();
 await nav('План подготовки').click();
 report.planButtons=await page.getByRole('button').allTextContents();
 await fs.writeFile(path.join(out,'progress.json'),JSON.stringify(report,null,2));
 await button('Заполнить свободные дни').click();
 await page.waitForTimeout(600);const planned=await state();
 report.planDays=planned.planning.days;
 const entries=Object.values(planned.planning.days).flatMap(d=>d.entries);
 assert(entries.length>0);assert(!entries.some(e=>e.title===title || e.curriculumNodeId==='ege-math-1-1'));
 report.planLimitation='Выбранная карточка 1.1 является предварительным навыком и без ручного пропуска обычно не предлагается в начале 10 класса. UI подтвердил сохранение пропуска и отсутствие её в новом плане; причинное исключение проверено отдельно domain-тестами ege-skip-plan.';
 report.checks.push({name:'New automatic plan',topicSkipped:title,entries:entries.length,skips:planned.egeTopicSkips});
 await shot('02-plan-with-skipped-topic');
 await nav('Настройки').click();await button('Учебные сцены').click();
 await page.locator('.quality-options button').filter({hasText:'Низкое'}).click();
 await page.getByLabel('Уменьшить движение',{exact:false}).check();
 await page.waitForTimeout(400);const settings=(await state()).settings;
 assert.equal(settings.quality,'low');assert.equal(settings.reducedMotion,true);
 report.checks.push({name:'Low and reduced motion via controls',quality:settings.quality,reducedMotion:settings.reducedMotion});
 await shot('03-low-reduced-motion');
 await nav('Все темы ЕГЭ').click();if(await button('Общий каталог тем').isVisible())await button('Общий каталог тем').click();
 await page.locator('.studio-topic-card').first().locator('h2 button').click();
 report.sceneText=await page.locator('.studio-topic-detail').innerText();
 await shot('04-topic-low-motion');
 await page.locator('.studio-topic-detail details > summary').filter({hasText:'Визуальное знакомство с темой'}).click();
 const scene=page.locator('.curriculum-scene');await scene.scrollIntoViewIfNeeded();
 assert.match(await scene.getAttribute('class'),/cv-quality-low/);assert.match(await scene.getAttribute('class'),/cv-motion-off/);
 const before=await scene.locator('.cv-step-label').innerText();
 await page.waitForTimeout(1300);assert.equal(await scene.locator('.cv-step-label').innerText(),before);
 await scene.getByRole('button',{name:'Следующий шаг',exact:true}).click();
 const after=await scene.locator('.cv-step-label').innerText();assert.notEqual(after,before);
 await shot('05-low-motion-manual-frame');
 await scene.getByRole('button',{name:'Предыдущий шаг',exact:true}).click();assert.equal(await scene.locator('.cv-step-label').innerText(),before);
 report.checks.push({name:'Actual low/reduced-motion scene',before,after,manualBack:true,automaticMovement:false});
 assert.deepEqual(report.errors,[]);report.status='pass';
}catch(e){report.status='needs-review';report.failure=String(e.stack||e);if(page){report.visibleButtons=await page.getByRole('button').allTextContents().catch(()=>[]);await shot('failure').catch(()=>{});}process.exitCode=1;}
finally{if(app)await app.close().catch(()=>{});await fs.writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify({status:report.status,failure:report.failure,checks:report.checks},null,2));}
