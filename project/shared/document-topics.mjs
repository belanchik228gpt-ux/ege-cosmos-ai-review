export function authoredTopicMarkdown(id) {
  const topic = documentTopics[id];
  if (!topic) return '';
  return [
    '## Учебный разворот',
    topic.explanation,
    '### Определение',
    topic.definition,
    '### Полезный приём',
    topic.tip,
    '### Формула или вывод',
    topic.formula,
    '### Разобранные примеры',
    'Авторские учебные примеры Cosmos. Это разборы для обучения, а не решения или результаты ученика.',
    ...topic.examples.flatMap((example, index) => [
      `### Пример ${index + 1} · ${example.title}`,
      example.problem,
      ...example.steps.map((step, stepIndex) => `${stepIndex + 1}. ${step}`),
      `Ответ: ${example.result}`,
    ]),
    ...(topic.furtherExamples?.length
      ? [
          '## Дополнительные авторские примеры',
          'Эти разборы дополняют объяснение. Они не являются результатами ученика.',
          ...topic.furtherExamples.flatMap((example) => [
            `### ${example.title}`,
            example.problem,
            ...example.steps.map((step, index) => `${index + 1}. ${step}`),
            `Ответ: ${example.result}`,
          ]),
        ]
      : []),
    ...(topic.mistakes?.length
      ? ['## Ошибки, которых можно избежать', ...topic.mistakes.map((item) => `- ${item}`)]
      : []),
    ...(topic.selfCheck?.length
      ? [
          '## Самопроверка',
          'Сначала реши самостоятельно. Ответы находятся в следующем разделе. Чтение этого конспекта не подтверждает освоение темы.',
          ...topic.selfCheck.map((item, index) => `${index + 1}. ${item.question}`),
          '## Ответы для самопроверки',
          ...topic.selfCheck.map((item, index) => `${index + 1}. ${item.answer}`),
        ]
      : []),
  ].join('\n\n');
}

